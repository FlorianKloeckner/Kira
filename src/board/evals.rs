const fn flip(table: [isize; 64]) -> [isize; 64] {
    let mut flipped = [0; 64];
    let mut i = 0;
    while i < 64 {
        let rank = i / 8;
        let file = i % 8;
        let flipped_rank = 7 - rank;
        flipped[flipped_rank * 8 + file] = table[i];
        i += 1;
    }
    flipped
}

